// Generates the legacy-URL redirect map from the content model (single source of truth):
//   deploy/apache/.htaccess        -> 301 redirects + security headers + caching for Apache
//   docs/legacy-redirects.json     -> machine-readable map used by tests and documentation
// Run: node scripts/generate-redirects.mjs   (also runs automatically before `npm run build`)
import { mkdirSync, writeFileSync } from "node:fs";
import { services } from "../src/content/services.ts";
import { solutions } from "../src/content/solutions.ts";
import { industries } from "../src/content/industries.ts";

const fromContent = [
  ...services.map((p) => [p.legacyPath, `/services/${p.slug}/`]),
  ...solutions.map((p) => [p.legacyPath, `/solutions/${p.slug}/`]),
  ...industries.map((p) => [p.legacyPath, `/industries/${p.slug}/`]),
];

const manual = [
  ["/index.php", "/"],
  ["/index.html", "/"],
  ["/company-profile.php", "/company/about/"],
  ["/mission.php", "/company/mission-values/"],
  ["/it-services.php", "/company/clients-partners/"],
  ["/clients.php", "/company/clients-partners/"],
  ["/testimonials.php", "/company/testimonials/"],
  ["/employees.php", "/resources/employees/"],
  ["/careers.php", "/careers/"],
  ["/git-domestic-career.php", "/careers/"],
  ["/lca.php", "/compliance/lca/"],
  ["/engaging-with-us.php", "/contact/business-inquiries/"],
  ["/partnering-us.php", "/contact/partnerships/"],
  ["/contact.php", "/contact/"],
  ["/disclaimer.php", "/legal/disclaimer/"],
  // Legacy LCA row GIT-LCA-69 linked to a mistyped filename; point it at the real document.
  ["/images/lca_docs/I-200-24157-07185.pdf", "/images/lca_docs/I-200-24157-071855.pdf"],
];

const map = [...manual, ...fromContent];
const seen = new Set();
for (const [from] of map) {
  if (seen.has(from)) throw new Error(`Duplicate redirect source ${from}`);
  seen.add(from);
}

mkdirSync("docs", { recursive: true });
writeFileSync(
  "docs/legacy-redirects.json",
  JSON.stringify(
    {
      generated: "scripts/generate-redirects.mjs",
      status: 301,
      note: "Legacy PDFs under /images/ are served from their original paths (no redirect needed) except the one mistyped LCA link.",
      redirects: map.map(([from, to]) => ({ from, to })),
    },
    null,
    2,
  ) + "\n",
);

const esc = (p) => p.replace(/^\//, "").replace(/[.\-]/g, (c) => "\\" + c);

const htaccess = `# =============================================================================
# GenuineIT website — Apache configuration (generated by scripts/generate-redirects.mjs)
# Deploy alongside the static export in out/. Requires mod_rewrite and mod_headers.
# =============================================================================
Options -Indexes
DirectoryIndex index.html index.php
ErrorDocument 404 /404.html
AddDefaultCharset UTF-8

<IfModule mod_rewrite.c>
  RewriteEngine On

  # --- Canonical host + HTTPS (enable once TLS is confirmed on the host) ---------
  # RewriteCond %{HTTPS} off [OR]
  # RewriteCond %{HTTP_HOST} ^www\\.genuineitllc\\.com$ [NC]
  # RewriteRule ^ https://genuineitllc.com%{REQUEST_URI} [R=301,L]

  # --- Legacy URL redirects (301) ---------------------------------------------
${map.map(([from, to]) => `  RewriteRule ^${esc(from)}$ ${to} [R=301,L]`).join("\n")}

  # --- Retired legacy endpoints ------------------------------------------------
  RewriteRule ^captcha\\.php$ - [G,L]
  # NOTE: /gitdocs/ (legacy sign-in area) is intentionally left untouched.
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), interest-cohort=()"
  Header always set Cross-Origin-Opener-Policy "same-origin"
  # Next.js static export inlines its bootstrap scripts, so 'unsafe-inline' is required for scripts.
  Header always set Content-Security-Policy "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'self'; frame-src 'none'; frame-ancestors 'self'; form-action 'self'; base-uri 'self'; object-src 'none'; upgrade-insecure-requests"
  # Enable after HTTPS is verified on every subdomain:
  # Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"

  <FilesMatch "\\.(html)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType image/png "access plus 1 month"
  ExpiresByType image/jpeg "access plus 1 month"
  ExpiresByType application/pdf "access plus 1 week"
</IfModule>
<IfModule mod_headers.c>
  <If "%{REQUEST_URI} =~ m#^/_next/static/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml text/xml application/xml text/plain
</IfModule>

# Only the inquiry handler may be executed from /api/.
<If "%{REQUEST_URI} =~ m#^/api/# && %{REQUEST_URI} !~ m#^/api/inquiry\\.php$#">
  Require all denied
</If>
`;
mkdirSync("deploy/apache", { recursive: true });
writeFileSync("deploy/apache/.htaccess", htaccess);
console.log(`generate-redirects: ${map.length} redirects written`);
